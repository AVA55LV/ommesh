def normalized(value):
    return tuple(ord(char) for char in value if ord(char) != 0xFE0F)


def array(name, item_type, values, render, per_line):
    lines = [f"static const {item_type} {name}[] = {{"]
    for start in range(0, len(values), per_line):
        lines.append("    " + ", ".join(render(value) for value in values[start:start + per_line]) + ",")
    return "\n".join(lines + ["};", ""])


def build(source, archive_path):
    old = source.read_text().split("emojiCodes[] = {", 1)[1].split("};", 1)[0]
    known = {(int(value, 16),) for value in re.findall(r"0x([a-f0-9]+)", old)}
    entries = []
    group_offsets = [0]
    sequence_offsets = [0]
    sequence = []
    pixel_offsets = [0]
    pixels = bytearray()
    with tarfile.open(archive_path, "r:gz") as archive:
        images = {}
        for member in archive.getmembers():
            if not member.isfile() or "/assets/72x72/" not in member.name or not member.name.endswith(".png"):
                continue
            codes = tuple(int(part, 16) for part in Path(member.name).stem.split("-"))
            images[tuple(code for code in codes if code != 0xFE0F)] = member
        for group in GROUPS:
            for value in group:
                key = normalized(value)
                if key in known:
                    continue
                if key not in images:
                    raise ValueError(f"Twemoji archive lacks {value!r} ({key!r})")
                entries.append(key)
                known.add(key)
                sequence.extend(map(ord, value))
                sequence_offsets.append(len(sequence))
                data = archive.extractfile(images[key]).read()
                with Image.open(io.BytesIO(data)) as art:
                    sprite = art.convert("RGBA").resize((24, 24), Image.Resampling.LANCZOS)
                    sprite = sprite.quantize(colors=24, method=Image.Quantize.FASTOCTREE).convert("RGBA")
                    rgba = sprite.tobytes()
                pixels.extend(struct.pack(">I", len(rgba)))
                pixels.extend(zlib.compress(rgba, 9))
                pixel_offsets.append(len(pixels))
            group_offsets.append(len(entries))
    order = sorted(range(len(entries)), key=entries.__getitem__)
    return "\n".join((
        "// Generated by tools/generate_chat_emoji.py from Twemoji v15.1.0.",
        "// Graphics copyright Twitter, Inc. and other contributors, CC BY 4.0.",
        "// Attribution: licenses/Twemoji.txt\n",
        array("extraEmojiGroupOffsets", "quint16", group_offsets, str, 12),
        array("extraEmojiSequenceOffsets", "quint16", sequence_offsets, str, 12),
        array("extraEmojiSequence", "uint", sequence, hex, 11),
        array("extraEmojiLookup", "quint16", order, str, 12),
        array("extraEmojiPixelOffsets", "quint32", pixel_offsets, str, 11),
        array("extraEmojiPixels", "uchar", pixels, str, 26),
    ))


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, help="Twemoji v15.1.0 codeload .tar.gz")
    parser.add_argument("--output", type=Path, default=root / "src/chat_emoji_extra.inc")
    args = parser.parse_args()
    args.output.write_text(build(root / "src/chat_emoji_data.inc", args.archive), encoding="utf-8")
